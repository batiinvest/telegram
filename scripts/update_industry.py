ok = 0
fail = 0
for code, ind, sub in MAPPING:
    res = sb.table('companies').update({'industry': ind, 'sub_industry': sub}) \
        .eq('code', code).eq('is_monitored', True).execute()
    if res.data:
        print(f"  ✅ {code}: {ind}/{sub}")
        ok += 1
    else:
        # .KS/.KQ 버전도 시도
        for suffix in ['.KS', '.KQ']:
            r2 = sb.table('companies').update({'industry': ind, 'sub_industry': sub}) \
                .eq('code', code+suffix).eq('is_monitored', True).execute()
            if r2.data:
                print(f"  ✅ {code+suffix}: {ind}/{sub}")
                ok += 1
                break
        else:
            print(f"  ⚠️  {code}: 매칭 없음")
            fail += 1

print(f"\n완료: {ok}개 업데이트, {fail}개 미매칭")

