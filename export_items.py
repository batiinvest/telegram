def parse_spec(spec: str):
    """'imp:8708@US + 8708@MX' → ('imp', [{'hs':'8708','cn':'US','rg':''}, ...])"""
    flow = 'exp'
    if spec.startswith('imp:'):
        flow, spec = 'imp', spec[4:]
    parts = []
    for piece in spec.split('+'):
        piece = piece.strip()
        if not piece:
            continue
        rg = ''
        if '#' in piece:
            piece, rg = piece.split('#', 1)
        cn = ''
        if '@' in piece:
            piece, cn = piece.split('@', 1)
        parts.append({'hs': piece.strip(), 'cn': cn.strip(), 'rg': rg.strip()})
    return flow, parts


def items():
    """화면·수집용 목록 — [{id, tab, ord, name, co, note, flow, parts, orig, orig_last}]"""
    out = []
    for tab, rows in (('p', P), ('f', F)):
        for i, row in enumerate(rows):
            iid, name, co, spec, note, last = row[:6]
            orig = row[6] if len(row) > 6 else None
            flow, parts = parse_spec(spec)
            out.append({'id': iid, 'tab': tab, 'ord': i, 'name': name.strip(), 'co': co or None, 'note': note or None,
                        'flow': flow, 'parts': parts, 'orig': orig or [name], 'orig_last': last})
    return out


def lvl_of(part: dict) -> str:
    """부분 → 수집 계열: nat(전국 품목) · cnty(품목×국가) · sgg(6자리×시군구) · total(총수출)"""
    if part['hs'] == '*':
        return 'total'
    if part['rg']:
        return 'sgg'
    return 'cnty' if part['cn'] else 'nat'


def sgg_hs6(hs: str) -> list:
    """지역 부분의 HS → 시군구 API에 물을 6자리 목록"""
    if len(hs) >= 6:
        return [hs[:6]]
    return HS4_CHILDREN.get(hs, [])
