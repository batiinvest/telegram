def test_parse_share_cancellation_duplicate_key():
    """'보통주식(주)'가 소각 수량·발행주식총수 두 행에 있어 KV에선 발행주식총수만 남는다 → 원문에서."""
    kv = {
        "_html": ("<tr><td>1. 소각할 주식의 종류와 수</td><td>보통주식(주)</td><td>630,904</td></tr>"
                  "<tr><td>2. 발행주식총수</td><td>보통주식(주)</td><td>89,862,944</td></tr>"),
        "1. 소각할 주식의 종류와 수": "보통주식(주)", "보통주식(주)": "89,862,944",
        "4. 소각예정금액(원)": "2,504,999,354",
    }
    assert parse_share_cancellation(kv)[0] == "🔥 소각주식: 보통주 630,904주"


def test_parse_major_shareholder_change_summary_after():
    """변경후 최대주주가 관계표에 없을 때 요약표 '변경후' 행을 쓴다(변경전 이름이 나가던 것)."""
    kv = {
        "1. 변경내용": "변경전", "최대주주등": "㈜비지에프에코머티리얼즈",
        "소유주식수(주)": "9,113,891", "소유비율(%)": "56.89", "변경후": "최대주주등 ㈜비지에프",
        "㈜비지에프에코머티리얼즈": "변경전 최대주주", "9,113,891": "56.89",
    }
    lines = parse_major_shareholder_change(kv)
    assert "  변경전: ㈜비지에프에코머티리얼즈 (9,113,891주 / 56.89%)" in lines
    assert "  변경후: ㈜비지에프" in lines


