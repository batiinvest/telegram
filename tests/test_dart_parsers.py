def test_parse_dividend_full():
    kv = {
        "1. 배당구분": "결산배당",
        "2. 배당종류": "현금배당",
        "1주당 배당금(원)": "보통주식 233",
        "시가배당률(%)": "보통주식 1.5",
        "배당금총액(원)": "15000000000",
        "배당기준일": "2025-12-31",
        "배당금지급 예정일자": "2026-04-15",
        "이사회결의일(결정일)": "2026-02-10",
    }
    assert parse_dividend(kv) == [
        "💰 결산배당 · 현금배당",
        "💵 1주당 233원 (시가배당률 1.5%)",
        "💰 배당총액: 150억원",
        "📅 배당기준일: 2025-12-31",
        "📅 지급예정: 2026-04-15",
        "📋 결의일: 2026-02-10",
    ]


