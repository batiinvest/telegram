# -*- coding: utf-8 -*-
"""dart_parsers characterization 테스트 — 공시 파서(kv dict → 텔레그램 라인).

dart_parsers는 최대 파일(2,767줄)이자 분할 예정(고위험 보류) 대상.
파서는 순수 함수(kv dict 입력 → list[str] 출력)라 실 HTML 없이 픽스처로 검증 가능.
분할 리팩토링 시 출력 텍스트가 바뀌면(=사용자에게 가는 메시지 변화) 즉시 포착한다.
기대값은 2026-07-25 실제 실행 출력에서 캡처.
"""
from dart_parsers import (
    parse_dividend, parse_treasury_acquisition, parse_share_cancellation,
    parse_record_date, parse_lawsuit, parse_embezzlement, parse_bonus_issue,
)


def test_parse_dividend_full():
    kv = {
        "1. 배당구분": "결산배당",
        "2. 배당종류": "현금배당",
        "1주당 배당금(원)": "보통주식 233",
        "시가배당률(%)": "보통주식 1.5",
        "배당금총액(원)": "15000000000",
        "배당기준일": "2025-12-31",
        "배당금지급 예정일자": "2026-04-15",
        "이사회결의일(결정일)": "2026-02-10",
    }
    assert parse_dividend(kv) == [
        "💰 결산배당 · 현금배당",
        "💵 1주당 233원 (시가배당률 1.5%)",
        "💰 배당총액: 150억원",
        "📅 배당기준일: 2025-12-31",
        "📅 지급예정: 2026-04-15",
        "📋 결의일: 2026-02-10",
    ]


def test_parse_dividend_minimal():
    """배당구분만 있으면 헤더 한 줄만."""
    assert parse_dividend({"1. 배당구분": "결산배당"}) == ["💰 결산배당"]


def test_parse_dividend_empty():
    """빈 kv → 빈 리스트 (graceful)."""
    assert parse_dividend({}) == []


def test_parse_treasury_acquisition():
    """자기주식 취득 — 영문 폼 키. 수탁사 괄호 이후 제거."""
    kv = {
        "1. Contract amount (KRW)": "10000000000",
        "9. Number of shares to be acquired": "500,000",
        "10. Price of shares to be acquired": "20,000",
        "Start date": "2026-02-11", "End date": "2026-05-10",
        "3. Purpose of contract": "주주가치 제고",
        "4. Counterparty (Trust company)": "삼성증권 (Samsung Securities)",
        "7. Board resolution date": "2026-02-10",
    }
    assert parse_treasury_acquisition(kv) == [
        "💰 취득금액: 100억원",
        "🔢 취득예정: 500,000주 (주당 20,000원)",
        "📅 계약기간: 2026-02-11 ~ 2026-05-10",
        "📋 목적: 주주가치 제고",
        "🏦 수탁사: 삼성증권",   # 영문 괄호 제거됨
        "📋 결의일: 2026-02-10",
    ]


def test_parse_share_cancellation():
    """주식소각 — 종류·수 필드에서 수량 추출(폴백 경로)."""
    kv = {
        "소각할 주식의 종류와 수": "보통주 1,000,000",
        "소각예정금액(원)": "20000000000",
        "소각할 주식의 취득방법": "기취득 자기주식",
        "소각 예정일": "2026-03-15",
        "이사회결의일(결정일)": "2026-02-10",
    }
    assert parse_share_cancellation(kv) == [
        "🔥 소각주식: 보통주 1,000,000주",
        "💰 소각예정금액: 200억원",
        "📋 취득방법: 기취득 자기주식",
        "📅 소각예정일: 2026-03-15",
        "📋 결의일: 2026-02-10",
    ]


def test_parse_record_date():
    """기준일 설정 — 기준일·사유·결의일."""
    kv = {"1. 기준일": "2025-12-31", "3. 설정사유": "정기주주총회 권리주주 확정",
          "4. 이사회결의일": "2025-11-20"}
    assert parse_record_date(kv) == [
        "📅 기준일: 2025-12-31",
        "📋 사유: 정기주주총회 권리주주 확정",
        "📋 결의일: 2025-11-20",
    ]


def test_parse_lawsuit():
    """소송 제기 — 청구금액 조 단위 포맷 + 자기자본 대비."""
    kv = {
        "사건의 명칭": "손해배상청구의 소", "원고ㆍ신청인": "홍길동 외 3인",
        "청구금액(원)": "1,500,000,000", "자기자본대비(%)": "2.3",
        "판결ㆍ결정내용": "피고는 원고에게 금원을 지급하라", "관할법원": "서울중앙지방법원",
        "향후대책": "법무법인을 통해 적극 대응 예정", "제기일자": "2025-11-15",
    }
    assert parse_lawsuit(kv) == [
        "⚖️ 사건: 손해배상청구의 소",
        "👤 원고: 홍길동 외 3인",
        "💰 청구금액: 15억원 (자기자본 대비 2.3%)",
        "📋 내용: 피고는 원고에게 금원을 지급하라",
        "🏛 관할: 서울중앙지방법원",
        "🧭 대책: 법무법인을 통해 적극 대응 예정",
        "📅 일자: 2025-11-15",
    ]


def test_parse_embezzlement():
    """횡령·배임 — 대상자(관계)·혐의금액."""
    kv = {
        "사고자": "김철수", "회사와의 관계": "전 대표이사",
        "혐의발생금액(원)": "800,000,000", "자기자본대비(%)": "1.2",
        "혐의내용": "회사 자금 횡령 혐의", "진행상황": "수사기관 고발 완료",
        "확인일자": "2025-11-10",
    }
    assert parse_embezzlement(kv) == [
        "👤 대상: 김철수 (전 대표이사)",
        "💸 혐의금액: 8억원 (자기자본 대비 1.2%)",
        "📋 혐의: 회사 자금 횡령 혐의",
        "🧭 조치: 수사기관 고발 완료",
        "📅 확인일: 2025-11-10",
    ]


def test_parse_bonus_issue():
    """무상증자 — _html 텍스트에서 배정비율·신주수·기준일·발행주식 증가 파싱."""
    html = ("1주당 신주배정 주식수 보통주식(주) 0.05 "
            "신주의 종류와 수 보통주식(주) 1,000,000 "
            "신주배정기준일 2026년 1월 15일 상장 예정일 2026년 2월 3일 "
            "보통주(자기주식 제외) 20,000,000 1,000,000 21,000,000 "
            "이사회결의일(결정일) 2025년 12월 20일")
    assert parse_bonus_issue({"_html": html}) == [
        "🎁 무상배정: 1주당 0.05주",
        "📊 신주: 보통 1,000,000주",
        "📅 배정기준 2026-01-15 | 상장 2026-02-03",
        "📦 발행주식: 20,000,000 → 21,000,000주 (+5.0%)",
        "📅 결의일: 2025-12-20",
    ]
