def test_parse_bonus_issue():
    """무상증자 — _html 텍스트에서 배정비율·신주수·기준일·발행주식 증가 파싱."""
    html = ("1주당 신주배정 주식수 보통주식(주) 0.05 "
            "신주의 종류와 수 보통주식(주) 1,000,000 "
            "신주배정기준일 2026년 1월 15일 상장 예정일 2026년 2월 3일 "
            "보통주(자기주식 제외) 20,000,000 1,000,000 21,000,000 "
            "이사회결의일(결정일) 2025년 12월 20일")
    assert parse_bonus_issue({"_html": html}) == [
        "🎁 무상배정: 1주당 0.05주",
        "📊 신주: 보통 1,000,000주",
        "📅 배정기준 2026-01-15 | 상장 2026-02-03",
        "📦 발행주식: 20,000,000 → 21,000,000주 (+5.0%)",
        "📅 결의일: 2025-12-20",
    ]


# ── 2026-10 발송분 감사에서 나온 값 오류 (실제 공시 키·값 그대로) ──────────────

_AMEND_KEY = "2. 계약내역 확정 계약금액 계약금액 총액(원) 매출액 대비(%)"   # 에이직랜드 20261013900236


def test_sub_parts_space_separated():
    """정정표 한 칸에 값이 공백으로만 이어진 경우 — ' - ' 없는 키·있는 키 모두 하위 항목별로."""
    assert _sub_parts("정정후_" + _AMEND_KEY, "13,450,153,298 13,450,153,298 14.3") == [
        ("확정 계약금액", "13,450,153,298"), ("계약금액 총액(원)", "13,450,153,298"),
        ("매출액 대비(%)", "14.3")]
    dash = "정정후_2. 계약내역 - 확정 계약금액 - 계약금액 총액(원) - 매출액 대비(%)"
    assert _sub_parts(dash, "19,658,441,088 19,658,441,088 29.55")[1] == ("계약금액 총액(원)", "19,658,441,088")
    # 서술형 값은 공백이 의미 — 나누지 않는다
    assert _sub_parts("정정후_6. 주요 계약조건 - 대금 - 조건", "인도일 기준 익월 말") is None


