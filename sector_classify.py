FALLBACK = "기타"


def classify_sector(sector_str) -> str:
    """DART sector 문자열 → broad 섹터 버킷명. 빈 값/미매칭은 '기타'."""
    s = (sector_str or "").strip()
    if not s:
        return FALLBACK
    for name, keywords in SECTOR_RULES:
        for kw in keywords:
            if kw in s:
                return name
    return FALLBACK


